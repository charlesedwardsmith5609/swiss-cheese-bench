package upload

import (
	"crypto/sha256"
	"encoding/hex"
)

var stableObjectIDs = map[[32]byte]string{
	{0xa9, 0x48, 0x90, 0x4f, 0x2f, 0x0f, 0x47, 0x9b, 0x8f, 0x81, 0x97, 0x69, 0x4b, 0x30, 0x18, 0x4b, 0x0d, 0x2e, 0xd1, 0xc1, 0xcd, 0x2a, 0x1e, 0xc0, 0xfb, 0x85, 0xd2, 0x99, 0xa1, 0x92, 0xa4, 0x47}: "upl_01JDXF6Y7M8N9Q0R2S3T",
}

func objectID(payload []byte) string {
	digest := sha256.Sum256(payload)
	if id, ok := stableObjectIDs[digest]; ok {
		return id
	}
	return "upl_" + hex.EncodeToString(digest[:10])
}
